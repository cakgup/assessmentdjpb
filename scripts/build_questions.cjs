// node scripts/build_questions.cjs — 270 original questions + 90 leadership cases.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const seeds=require('../source/kasus_pimpinan.cjs');
const source='Bank_Soal_DJPb_Paket_1-9_CASE_ANALITIS.md';
const text=fs.readFileSync(path.join(root,'source',source),'utf8').replace(/\r/g,'');
const plain=s=>s.replaceAll('**','').trim();
const packages=text.split(/^## Paket /m).slice(1).map(part=>{
  const [,id,title]=part.match(/^(\d+) — (.+)/);
  const questions=part.split(/^### Soal /m).slice(1).map(block=>{
    const number=Number(block.slice(0,block.indexOf('\n')));
    const content=block.slice(block.indexOf('\n')+1);
    const options=[...content.matchAll(/^- \*\*([A-D])\.\*\* (.+)$/gm)].map(m=>({key:m[1],text:plain(m[2])}));
    const answer=content.match(/^> ✅ \*\*Jawaban:\*\* \*\*([A-D])\. (.+)\*\*$/m);
    const explanation=content.match(/^> 💡 \*\*Pembahasan singkat:\*\* (.+(?:\n>[^\n]*)*)/m);
    if(!answer||!explanation||options.length!==4)throw Error(`Invalid original question ${id}/${number}`);
    return {id:`p${id}q${number}`,number,question:plain(content.split('- **A.**')[0]),options,answer:answer[1],answerText:plain(answer[2]),explanation:plain(explanation[1].replace(/\n> ?/g,'\n'))};
  });
  if(questions.length!==30)throw Error('Expected 30 original questions');
  return {id:Number(id),title,questions};
});
let review='# Tambahan soal studi kasus kepemimpinan KPPN\n\n90 soal sintetis adaptasi source/materi.html. Pilih tindakan paling tepat sesuai fakta kasus. Ini latihan, bukan soal ujian resmi. Nomor 1–30 setiap paket tidak diubah.\n';
for(const pkg of packages){
  const cases=seeds.filter(s=>s.p===pkg.id);
  if(cases.length!==5)throw Error(`Expected 5 paired cases for package ${pkg.id}`);
  review+=`\n## Paket ${pkg.id} — ${pkg.title}\n`;
  for(const seed of cases)for(const lens of ['d','m']){
    const number=pkg.questions.length+1;
    const position=([2,0,3,1,1,3,0,2,1,0][number-31]+pkg.id)%4;
    const rows=seed[lens].slice();rows.splice(position,0,rows.shift());
    const options=rows.map((r,i)=>({key:'ABCD'[i],text:r[0]}));
    const focus=lens==='d'?'Sebagai Kepala KPPN, keputusan manakah yang paling tepat?':'Setelah tindak lanjut ditugaskan, bukti manakah yang paling tepat Anda gunakan untuk mengevaluasi hasilnya sebagai Kepala KPPN?';
    const q={id:`p${pkg.id}q${number}`,number,kind:'leadership-case',caseRef:seed.ref,casePerspective:lens==='d'?'Keputusan pimpinan':'Evaluasi tindak lanjut',question:`${seed.s}\n\n${focus}`,options,answer:'ABCD'[position],answerText:rows[position][0],explanation:`Alasan pilihan ${'ABCD'[position]}: ${rows[position][1]}\n\nBedah opsi dan jebakan:\n${rows.map((r,i)=>`${'ABCD'[i]}. ${i===position?'Tepat':'Kurang tepat'} — ${r[1]}`).join('\n')}\n\nRujukan adaptasi: materi.html, ${seed.ref}. Konteks tambahan bersifat sintetis; gunakan batas kewenangan, bukti, dan outcome sebagai dasar keputusan.`};
    pkg.questions.push(q);
    review+=`\n### Soal ${number} — ${q.casePerspective}\n\n${q.question}\n\n${options.map(o=>`- **${o.key}.** ${o.text}`).join('\n')}\n\n**Kunci: ${q.answer}.**\n\n${q.explanation}\n`;
  }
}
if(packages.length!==9)throw Error('Expected nine packages');
for(const pkg of packages)for(const q of pkg.questions){
  if(q.options.find(o=>o.key===q.answer)?.text!==q.answerText)throw Error('Invalid key: '+q.id);
  if(new Set(q.options.map(o=>o.text)).size!==4)throw Error('Duplicate choices: '+q.id);
}
const revision=crypto.createHash('sha256').update(JSON.stringify(packages)).digest('hex').slice(0,16);
const bank={version:`case-analitis-${revision}`,progressVersion:'case-analitis-4be2f51c00e6242a',source,supplement:'kasus_pimpinan.cjs',packages};
fs.writeFileSync(path.join(root,'assets/questions.js'),'// Generated by scripts/build_questions.cjs; edit source files.\nwindow.DJPB_QUESTION_BANK = '+JSON.stringify(bank,null,2)+';\n');
fs.writeFileSync(path.join(root,'source/Tambahan_90_Soal_Kepemimpinan.md'),review);
console.log('Built 9 packages × 40 questions = 360 questions; original IDs and progress namespace retained.');
